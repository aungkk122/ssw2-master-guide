const SORTED_DICT_KEYS = Object.keys(FURIGANA_DICT).sort((a, b) => b.length - a.length);

/**
 * Segments a Japanese string into RubyToken items so every Kanji sequence is annotated with its Furigana reading.
 * If text already has inline parenthesized furigana like "預り金（あずかりきん）", it uses that reading directly
 * and avoids duplicating the parenthesized reading when furigana is enabled.
 */
export function segmentFurigana(input: string): RubyToken[] {
  if (!input) return [];

  const tokens: RubyToken[] = [];
  let i = 0;

  while (i < input.length) {
    // Check if there is an explicit Kanji + （かな） pattern starting at i (Kana only, not English)
    const rest = input.slice(i);
    const explicitMatch = rest.match(/^([\u4E00-\u9FAF\u3005\u3040-\u309F0-9]+?)（([\u3040-\u309F\u30FC・\s\/]+)）/);
    if (explicitMatch && /[\u4E00-\u9FAF]/.test(explicitMatch[1])) {
      tokens.push({
        text: explicitMatch[1],
        reading: explicitMatch[2]
      });
      i += explicitMatch[0].length;
      continue;
    }

    // Check longest matching dictionary entry starting at i
    let matchedKey: string | null = null;
    if (/[\u4E00-\u9FAF0-9]/.test(input[i])) {
      for (const key of SORTED_DICT_KEYS) {
        if (input.startsWith(key, i)) {
          matchedKey = key;
          break;
        }
      }
    }

    if (matchedKey) {
      tokens.push({
        text: matchedKey,
        reading: FURIGANA_DICT[matchedKey]
      });
      i += matchedKey.length;
    } else {
      // Collect consecutive non-matching characters
      if (tokens.length > 0 && !tokens[tokens.length - 1].reading) {
        tokens[tokens.length - 1].text += input[i];
      } else {
        tokens.push({ text: input[i] });
      }
      i += 1;
    }
  }

  return tokens;
}
